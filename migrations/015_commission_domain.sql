CREATE TABLE IF NOT EXISTS commission_rules (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  barbearia_id INT UNSIGNED NOT NULL,
  profissional_id INT UNSIGNED NULL,
  servico_id INT UNSIGNED NULL,
  scope_key VARCHAR(80) NOT NULL,
  tipo ENUM('percentage','fixed') NOT NULL,
  valor DECIMAL(12,2) NOT NULL,
  valor_bps SMALLINT UNSIGNED NULL,
  base ENUM('gross','net_after_discount') NULL,
  valido_de DATETIME NULL,
  valido_ate DATETIME NULL,
  ativo TINYINT(1) NOT NULL DEFAULT 1,
  versao INT UNSIGNED NOT NULL DEFAULT 1,
  criado_por INT UNSIGNED NULL,
  criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_commission_rule_version (barbearia_id, scope_key, valido_de, versao),
  KEY idx_commission_rule_lookup (barbearia_id, profissional_id, servico_id, ativo, valido_de),
  CONSTRAINT fk_commission_rule_business FOREIGN KEY (barbearia_id) REFERENCES barbearias (id) ON DELETE RESTRICT,
  CONSTRAINT fk_commission_rule_professional FOREIGN KEY (profissional_id) REFERENCES colaboradores (id) ON DELETE RESTRICT,
  CONSTRAINT fk_commission_rule_service FOREIGN KEY (servico_id) REFERENCES servicos (id) ON DELETE RESTRICT,
  CONSTRAINT fk_commission_rule_creator FOREIGN KEY (criado_por) REFERENCES usuarios (id) ON DELETE SET NULL,
  CONSTRAINT chk_commission_rule_value CHECK (valor >= 0),
  CONSTRAINT chk_commission_rule_percent CHECK ((tipo = 'fixed' AND valor_bps IS NULL) OR (tipo = 'percentage' AND valor_bps BETWEEN 0 AND 10000)),
  CONSTRAINT chk_commission_rule_dates CHECK (valido_ate IS NULL OR valido_de IS NULL OR valido_ate > valido_de)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS commission_entitlements (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  barbearia_id INT UNSIGNED NOT NULL,
  agendamento_id INT UNSIGNED NOT NULL,
  servico_id INT UNSIGNED NOT NULL,
  profissional_id INT UNSIGNED NOT NULL,
  rule_id BIGINT UNSIGNED NULL,
  completed_at DATETIME NOT NULL,
  gross_amount DECIMAL(12,2) NOT NULL,
  discount_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
  original_net_amount DECIMAL(12,2) NOT NULL,
  total_commission DECIMAL(12,2) NOT NULL,
  snapshot_json JSON NOT NULL,
  calculation_version VARCHAR(30) NOT NULL,
  revision INT UNSIGNED NOT NULL DEFAULT 1,
  status ENUM('pending_rule','open','reserved','settled','reversed') NOT NULL DEFAULT 'open',
  criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_commission_entitlement_item (barbearia_id, agendamento_id, servico_id, profissional_id, revision),
  KEY idx_commission_entitlement_period (barbearia_id, profissional_id, completed_at, status),
  CONSTRAINT fk_commission_entitlement_business FOREIGN KEY (barbearia_id) REFERENCES barbearias (id) ON DELETE RESTRICT,
  CONSTRAINT fk_commission_entitlement_appointment FOREIGN KEY (agendamento_id) REFERENCES agendamentos (id) ON DELETE RESTRICT,
  CONSTRAINT fk_commission_entitlement_service FOREIGN KEY (servico_id) REFERENCES servicos (id) ON DELETE RESTRICT,
  CONSTRAINT fk_commission_entitlement_professional FOREIGN KEY (profissional_id) REFERENCES colaboradores (id) ON DELETE RESTRICT,
  CONSTRAINT fk_commission_entitlement_rule FOREIGN KEY (rule_id) REFERENCES commission_rules (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS commission_entries (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  barbearia_id INT UNSIGNED NOT NULL,
  entitlement_id BIGINT UNSIGNED NOT NULL,
  profissional_id INT UNSIGNED NOT NULL,
  agendamento_id INT UNSIGNED NOT NULL,
  payment_id BIGINT UNSIGNED NULL,
  refund_id BIGINT UNSIGNED NULL,
  kind ENUM('release','reversal','manual_adjustment','correction') NOT NULL,
  signed_amount DECIMAL(12,2) NOT NULL,
  source_event_id VARCHAR(120) NOT NULL,
  idempotency_key VARCHAR(120) NOT NULL,
  reason VARCHAR(240) NULL,
  criado_por INT UNSIGNED NULL,
  effective_at DATETIME NOT NULL,
  criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_commission_entry_idempotency (barbearia_id, idempotency_key),
  KEY idx_commission_entry_ledger (barbearia_id, profissional_id, effective_at, kind),
  CONSTRAINT fk_commission_entry_business FOREIGN KEY (barbearia_id) REFERENCES barbearias (id) ON DELETE RESTRICT,
  CONSTRAINT fk_commission_entry_entitlement FOREIGN KEY (entitlement_id) REFERENCES commission_entitlements (id) ON DELETE RESTRICT,
  CONSTRAINT fk_commission_entry_professional FOREIGN KEY (profissional_id) REFERENCES colaboradores (id) ON DELETE RESTRICT,
  CONSTRAINT fk_commission_entry_appointment FOREIGN KEY (agendamento_id) REFERENCES agendamentos (id) ON DELETE RESTRICT,
  CONSTRAINT fk_commission_entry_payment FOREIGN KEY (payment_id) REFERENCES payments (id) ON DELETE RESTRICT,
  CONSTRAINT fk_commission_entry_refund FOREIGN KEY (refund_id) REFERENCES refunds (id) ON DELETE RESTRICT,
  CONSTRAINT fk_commission_entry_creator FOREIGN KEY (criado_por) REFERENCES usuarios (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS commission_settlements (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  barbearia_id INT UNSIGNED NOT NULL,
  profissional_id INT UNSIGNED NOT NULL,
  periodo_inicio DATETIME NOT NULL,
  periodo_fim DATETIME NOT NULL,
  status ENUM('draft','closed','partially_paid','paid','cancelled') NOT NULL DEFAULT 'closed',
  total_lancamentos DECIMAL(12,2) NOT NULL DEFAULT 0,
  total_adiantamentos DECIMAL(12,2) NOT NULL DEFAULT 0,
  total_pago DECIMAL(12,2) NOT NULL DEFAULT 0,
  saldo_a_pagar DECIMAL(12,2) NOT NULL DEFAULT 0,
  criado_por INT UNSIGNED NULL,
  fechado_em DATETIME NULL,
  cancelado_em DATETIME NULL,
  motivo_cancelamento VARCHAR(240) NULL,
  criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_commission_settlement_lookup (barbearia_id, profissional_id, status, periodo_fim),
  CONSTRAINT fk_commission_settlement_business FOREIGN KEY (barbearia_id) REFERENCES barbearias (id) ON DELETE RESTRICT,
  CONSTRAINT fk_commission_settlement_professional FOREIGN KEY (profissional_id) REFERENCES colaboradores (id) ON DELETE RESTRICT,
  CONSTRAINT fk_commission_settlement_creator FOREIGN KEY (criado_por) REFERENCES usuarios (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS commission_settlement_items (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  settlement_id BIGINT UNSIGNED NOT NULL,
  entry_id BIGINT UNSIGNED NOT NULL,
  amount DECIMAL(12,2) NOT NULL,
  criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_commission_settlement_entry (entry_id),
  CONSTRAINT fk_commission_settlement_item_settlement FOREIGN KEY (settlement_id) REFERENCES commission_settlements (id) ON DELETE RESTRICT,
  CONSTRAINT fk_commission_settlement_item_entry FOREIGN KEY (entry_id) REFERENCES commission_entries (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS commission_advances (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  barbearia_id INT UNSIGNED NOT NULL,
  profissional_id INT UNSIGNED NOT NULL,
  financial_transaction_id BIGINT UNSIGNED NULL,
  valor DECIMAL(12,2) NOT NULL,
  pago_em DATETIME NOT NULL,
  metodo VARCHAR(30) NOT NULL,
  observacao VARCHAR(240) NULL,
  status ENUM('confirmed','reversed') NOT NULL DEFAULT 'confirmed',
  criado_por INT UNSIGNED NULL,
  criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_commission_advance_lookup (barbearia_id, profissional_id, pago_em, status),
  CONSTRAINT fk_commission_advance_business FOREIGN KEY (barbearia_id) REFERENCES barbearias (id) ON DELETE RESTRICT,
  CONSTRAINT fk_commission_advance_professional FOREIGN KEY (profissional_id) REFERENCES colaboradores (id) ON DELETE RESTRICT,
  CONSTRAINT fk_commission_advance_transaction FOREIGN KEY (financial_transaction_id) REFERENCES financial_transactions (id) ON DELETE RESTRICT,
  CONSTRAINT fk_commission_advance_creator FOREIGN KEY (criado_por) REFERENCES usuarios (id) ON DELETE SET NULL,
  CONSTRAINT chk_commission_advance_amount CHECK (valor > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS commission_advance_allocations (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  barbearia_id INT UNSIGNED NOT NULL,
